package proxy

import (
	"fmt"
	"net/http"
	"net/url"
	"regexp"
)

// Endpoints for pointing apt at this instance:
//
//	GET /_apt.conf   apt configuration for /etc/apt/apt.conf.d/
//	GET /_setup.sh   shell script that installs (or with "remove" removes) that file
//
// Names start with "_" so they can never collide with a mirror host in prefix mode.

// validHostPort accepts host names, IPv4 and bracketed IPv6 addresses with an optional
// port, and nothing else. The value ends up inside a config file and a shell script
// that people pipe into sh, while the Host header is chosen by the client.
var validHostPort = regexp.MustCompile(`^([A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?|\[[0-9A-Fa-f:.]+\])(:[0-9]{1,5})?$`).MatchString

// baseURL is the address clients should use to reach this instance: the configured
// public URL, else the host and port the request came in on.
func (s *Server) baseURL(r *http.Request) (string, bool) {
	if s.publicURL != "" {
		return s.publicURL, true
	}
	if !validHostPort(r.Host) {
		return "", false
	}
	return "http://" + r.Host, true
}

func parsePublicURL(raw string) (string, error) {
	if raw == "" {
		return "", nil
	}
	u, err := url.Parse(raw)
	if err != nil || u.Scheme != "http" || !validHostPort(u.Host) || (u.Path != "" && u.Path != "/") || u.RawQuery != "" || u.User != nil {
		return "", fmt.Errorf("public URL %q: want http://host[:port]", raw)
	}
	return "http://" + u.Host, nil
}

func aptConf(base string) string {
	return fmt.Sprintf("// Generated by apt-cachealot: send apt's http traffic through the cache.\n"+
		"// https:// sources are not cached this way, see the apt-cachealot README (prefix mode).\n"+
		"Acquire::http::Proxy %q;\n", base)
}

const setupScript = `#!/bin/sh
# Points apt at the apt-cachealot instance at %[1]s
#   install: curl -fsS %[1]s/_setup.sh | sh
#   remove:  curl -fsS %[1]s/_setup.sh | sh -s -- remove
set -eu
conf=${APT_CACHEALOT_CONF:-/etc/apt/apt.conf.d/01apt-cachealot}
dir=$(dirname "$conf")
if [ "${1:-}" = remove ]; then
  rm -f "$conf"
  echo "removed $conf"
  exit 0
fi
mkdir -p "$dir" 2>/dev/null || true
if [ ! -w "$dir" ]; then
  echo "apt-cachealot setup: cannot write to $dir, run as root" >&2
  exit 1
fi
cat > "$conf" <<'APT_CACHEALOT_EOF'
%[2]sAPT_CACHEALOT_EOF
echo "apt now uses the cache at %[1]s ($conf)"
`

func (s *Server) serveSetup(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodGet && r.Method != http.MethodHead {
		http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
		return
	}
	base, ok := s.baseURL(r)
	if !ok {
		http.Error(w, "cannot derive a safe address from the Host header; set -public-url", http.StatusBadRequest)
		return
	}
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Header().Set("Cache-Control", "no-store")
	conf := aptConf(base)
	if r.URL.Path == "/_setup.sh" {
		fmt.Fprintf(w, setupScript, base, conf)
		return
	}
	fmt.Fprint(w, conf)
}
